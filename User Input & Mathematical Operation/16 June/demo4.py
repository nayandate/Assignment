'''
Assignment 4: Area of Rectangle

Write a Python program that:

Accepts length and breadth.
Calculates area.

Input:
Length = 10
Breadth = 5

Output:
Area = 50
'''

length = int(input("Enter length of rectangle : "))
breadth = int(input("Enter breadth of rectangle : "))
area = length*breadth
print(f"Area = {area}")